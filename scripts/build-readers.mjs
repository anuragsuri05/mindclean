// Packages readers/readers.js for the mobile app: the reader functions become a
// script string the app injects into its hidden in-app browser, and the
// platform list becomes plain data. Run automatically by the mobile app's scripts.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PLATFORMS } from "../readers/readers.js";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = fs.readFileSync(path.join(root, "readers/readers.js"), "utf8");
const body = source.replace(/^export /gm, "");
const script = `(function(){${body}\nwindow.__mindcleanReaders = { extractFeed: extractFeed, looksLoggedIn: looksLoggedIn };})();`;

const meta = Object.fromEntries(
  Object.entries(PLATFORMS).map(([id, p]) => [
    id,
    { name: p.name, url: p.url, loginUrl: p.loginUrl, login: p.login ? p.login.source : null, host: p.host.source },
  ]),
);

// Test builds: MINDCLEAN_TEST_PLATFORMS=http://host:4100 points Instagram, LinkedIn
// and X at the mock platforms in testenv/mock-platforms.mjs. Never set for real builds.
const mock = process.env.MINDCLEAN_TEST_PLATFORMS;
if (mock) {
  const host = new URL(mock).hostname.replace(/\./g, "\\.");
  const routes = { instagram: ["/instagram/", "/instagram/accounts/login/"], linkedin: ["/linkedin/feed/", "/linkedin/login"], x: ["/x/home", "/x/i/flow/login"] };
  for (const [id, [home, login]] of Object.entries(routes)) {
    Object.assign(meta[id], { url: mock + home, loginUrl: mock + login, host: `^${host}$`, name: `${meta[id].name}` });
  }
}

const out = `// Generated by scripts/build-readers.mjs from readers/readers.js. Do not edit by hand.${mock ? `\n// TEST BUILD: Instagram, LinkedIn and X point at mock platforms (${mock}).` : ""}
export const READERS_SCRIPT = ${JSON.stringify(script)};

export const PLATFORM_META = ${JSON.stringify(meta, null, 2)} as const;

export type PlatformId = keyof typeof PLATFORM_META;
`;
fs.writeFileSync(path.join(root, "mobile/src/readers.generated.ts"), out);
console.log(`${mock ? "TEST " : ""}readers.generated.ts written (${(script.length / 1024).toFixed(1)} KB, ${Object.keys(meta).length} platforms)`);
